/**
 * Authentic Quran Uthmani Text and Tafsir Al-Muyassar Provider.
 * Combines curated offline text/tafsir for instant offline access
 * with a high-speed dynamic API fetcher for all 6,236 Quranic verses.
 */
object QuranTafsirRepository {

    private val cache = ConcurrentHashMap<String, AyahTafsirData>()

    private val httpClient = OkHttpClient.Builder()
        .connectTimeout(6, TimeUnit.SECONDS)
        .readTimeout(6, TimeUnit.SECONDS)
        .followRedirects(true)
        .build()

    // Pre-seeded authentic offline verses with Uthmani script and Tafsir Al-Muyassar
    init {
        seedOfflineVerses()
    }

    suspend fun getAyah(
        surahNumber: Int,
        ayahNumber: Int,
        ioDispatcher: CoroutineDispatcher = Dispatchers.IO
    ): AyahTafsirData {
        val key = "$surahNumber:$ayahNumber"
        cache[key]?.let { return it }

        return withContext(ioDispatcher) {
            // Fetch online via Al-Quran Cloud API (editions: quran-uthmani & ar.muyassar)
            try {
                val url = "https://api.alquran.cloud/v1/ayah/$surahNumber:$ayahNumber/editions/quran-uthmani,ar.muyassar"
                val request = Request.Builder()
                    .url(url)
                    .header("User-Agent", "QuranRadioApp/1.0")
                    .build()

                httpClient.newCall(request).execute().use { response ->
                    if (response.isSuccessful) {
                        val body = response.body?.string()
                        if (!body.isNullOrBlank()) {
                            val json = JSONObject(body)
                            if (json.optInt("code") == 200 && json.has("data")) {
                                val dataArr = json.getJSONArray("data")
                                var uthmaniText = ""
                                var tafsirText = ""

                                for (i in 0 until dataArr.length()) {
                                    val item = dataArr.getJSONObject(i)
                                    val edition = item.getJSONObject("edition")
                                    val identifier = edition.optString("identifier")
                                    val text = item.optString("text")

                                    if (identifier == "quran-uthmani") {
                                        uthmaniText = text
                                    } else if (identifier == "ar.muyassar") {
                                        tafsirText = text
                                    }
                                }

                                if (uthmaniText.isNotBlank()) {
                                    val result = AyahTafsirData(
                                        surahNumber = surahNumber,
                                        ayahNumber = ayahNumber,
                                        uthmaniText = uthmaniText,
                                        tafsirText = if (tafsirText.isNotBlank()) tafsirText else "التفسير الميسر: جاري تحميل البيان القرآني..."
                                    )
                                    cache[key] = result
                                    return@withContext result
                                }
                            }
                        }
                    }
                }
            } catch (_: Exception) {}

            // Fallback if offline and not in pre-seed
            AyahTafsirData(
                surahNumber = surahNumber,
                ayahNumber = ayahNumber,
                uthmaniText = "﴿ الآية رقم $ayahNumber من السورة المباركة ﴾",
                tafsirText = "التفسير الميسر: يُرجى الاتصال بالإنترنت لعرض التفسير الكامل بالرسم العثماني لهذه الآية."
            )
        }
    }

